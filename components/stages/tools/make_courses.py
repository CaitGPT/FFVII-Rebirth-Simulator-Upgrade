"""Build data/courses.json from the game's table CSVs.

    python tools/make_courses.py <DataTableIndex Input folder> [<English text map json>]

For every simulator course (Colosseum rows with IsVRMission 1) it lists the rounds' enemies and works out how much
clear, flat space the course needs around the stage's centre: the furthest of the simulator's own scripted points
that any of its enemies uses, or the ordinary spawn reach. Sources and reasoning: docs/research/VR-STAGE-AND-ARENAS.md
section 5. The CSVs and the text map are game-derived and stay outside this repository; the output holds only row
names, enemy template names, titles and numbers.
"""
import csv
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
csv.field_size_limit(10**9)

# Metres from the stage centre to the furthest scripted point each enemy uses in 0000-COMON_Btl_Navigation_Mod.
# Keyed by a pattern on the enemy template name.
REACH = [
    (r"_SU2040_", 28.3, "Phoenix's points"),
    (r"_PC0010_|Sephiroth", 26.5, "Sephiroth's magic points"),
    (r"_SU2010_|_SU2015_", 24.9, "Odin's points"),
    (r"_EN2216_", 22.4, "Mindflayer's warp points"),
    (r"_SU2030_", 22.0, "Alexander's points"),
    (r"_EN2255_", 15.7, "8eye's points"),
    (r"_SU20\d\d_", 14.0, "summon entrance point"),
]
MU_REACH = (18.0, "fixed pop points (UsePopTargetPoint)")
ORDINARY = (12.0, "ordinary spawns")
# Left out: the eight Shinra Manor courses (owner, 2026-11-16, confirmed 2026-11-17). The eleven tutorial courses
# (r"TutorialBtl") were left out too until 2026-11-17, when the owner asked for them to have the stages.
EXCLUDED = [
    (r"_NIBLS_", "Shinra Manor simulator (owner, 2026-11-16; confirmed 2026-11-17)"),
]


def table(path):
    rows = list(csv.reader(open(path, encoding="utf-8-sig")))
    return rows[0], rows[1:]


def array(header, row, name):
    start = header.index(name)
    end = start + 1
    while end < len(header) and header[end].isdigit():
        end += 1
    return [v for v in row[start:end] if v and not v.startswith("0    |")]


def main() -> int:
    source = pathlib.Path(sys.argv[1]) / "Resident"
    text = json.loads(pathlib.Path(sys.argv[2]).read_text(encoding="utf-8")) if len(sys.argv) > 2 else {}

    def english(key):
        return text.get(key) or text.get(key.lstrip("$")) or ""

    ch, courses = table(source / "Colosseum.csv")
    th, territories = table(source / "EnemyTerritory.csv")
    lh, levels = table(source / "EnemyTerritoryLevel.csv")
    territory = {r[1]: r for r in territories}
    level = {r[1]: dict(zip(lh, r)) for r in levels}
    out = []
    for row in courses:
        c = dict(zip(ch, row))
        if c["IsVRMission"] != "1":
            continue
        key = row[1]
        rounds = array(ch, row, "EnemyTerritoryID_Array")
        enemies, fixed_pop = [], False
        for name in rounds:
            t = territory.get(name)
            if t:
                enemies += array(th, t, "MobTemplateList_Array") + array(th, t, "WaveMobTemplateList_Array")
            if level.get(name, {}).get("UsePopTargetPoint") == "1":
                fixed_pop = True
        enemies = sorted(set(enemies))
        need, why = ORDINARY
        if fixed_pop and MU_REACH[0] > need:
            need, why = MU_REACH
        for pattern, reach, reason in REACH:
            if reach > need and any(re.search(pattern, e) for e in enemies):
                need, why = reach, reason
        excluded = next((reason for pattern, reason in EXCLUDED if re.search(pattern, key)), None)
        out.append({
            "key": key,
            "title_id": c["ItemName"],
            "title": english(c["ItemName"]),
            "rounds": len(rounds),
            "enemies": enemies,
            "needs_m": need,
            "needs_why": why,
            "excluded": excluded,
        })
    target = ROOT / "data" / "courses.json"
    target.write_text(json.dumps({
        "_about": "Generated by tools/make_courses.py from the game's tables. needs_m is the clear flat radius a "
                  "course wants around the stage centre.",
        "courses": out,
    }, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(out)} courses to {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
