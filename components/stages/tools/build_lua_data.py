"""Write Scripts/stage_data.lua from data/stages.json and data/courses.json.

    python tools/build_lua_data.py          # write the file
    python tools/build_lua_data.py --check  # fail if the file is out of date

Edit data/stages.json, never the generated Lua.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data" / "stages.json"
COURSES = ROOT / "data" / "courses.json"
MOD_COURSES = ROOT / "data" / "mod_courses.json"
TARGET = ROOT / "ue4ss" / "SimulatorStages" / "Scripts" / "stage_data.lua"


def lua(value, indent=0):
    pad = "    " * indent
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        if all(not isinstance(v, (dict, list)) for v in value):
            return "{ " + ", ".join(lua(v) for v in value) + " }"
        inner = ",\n".join(pad + "    " + lua(v, indent + 1) for v in value)
        return "{\n" + inner + ",\n" + pad + "}"
    if isinstance(value, dict):
        rows = []
        for key, item in value.items():
            if key.startswith("_") or item is None:
                continue
            name = key if key.isidentifier() else "[" + json.dumps(key) + "]"
            rows.append(pad + "    " + name + " = " + lua(item, indent + 1))
        return "{\n" + ",\n".join(rows) + ",\n" + pad + "}"
    raise TypeError(type(value))


def build() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    ids = [stage["id"] for stage in data["stages"]]
    if len(ids) != len(set(ids)) or "vanilla" in ids:
        raise SystemExit("duplicate or reserved stage id")
    courses = [
        {"key": c["key"], "title_id": c["title_id"], "title": c["title"], "needs_m": c["needs_m"], "excluded": c["excluded"]}
        for c in json.loads(COURSES.read_text(encoding="utf-8"))["courses"]
    ]
    # Courses other mods add (data/mod_courses.json), after the game's own
    courses += [
        {"key": c["key"], "title_id": c["title_id"], "title": c["title"], "needs_m": c["needs_m"], "excluded": c["excluded"]}
        for c in json.loads(MOD_COURSES.read_text(encoding="utf-8"))["courses"]
    ]
    titles = [c["title"] for c in courses]
    if len(titles) != len(set(titles)) or "" in titles:
        raise SystemExit("course titles must be unique and present")
    return (
        "-- Generated by tools/build_lua_data.py from data/stages.json and data/courses.json. Do not edit.\n"
        "return " + lua({"vr_stage": data["vr_stage"], "stages": data["stages"], "courses": courses}) + "\n"
    )


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("stage_data.lua is out of date: run tools/build_lua_data.py")
            return 1
        print("stage_data.lua is up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
