"""Assemble native/src/main.cpp from the parts of Junon Colosseum's helper that are proven in the game.

    python tools/make_helper_source.py <FFVII-Rebirth-Junon-Colosseum checkout>

Junon Colosseum's helper (experiments/junon-foyer/native/src/main.cpp) took a lot of live testing to make safe: this
game calls ProcessEvent from worker threads, and a level load from one of them crashes the async loader. Rather than
rewrite that, this script copies four sections of it unchanged (the game-thread check, the code-byte checks, the
loader-idle check and the safe-point gate), and wraps them with this mod's own small request loop (helper_glue.cpp).
find_addresses.hpp started as a copy of Junon's and is now kept here (see the note at its end). Both repositories are
ours.

Re-run it when Junon's helper gains a fix in one of those sections; the line anchors below are checked, so a moved
section stops the script instead of copying the wrong lines.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
source_dir = pathlib.Path(sys.argv[1]) / "experiments" / "junon-foyer" / "native" / "src"
lines = (source_dir / "main.cpp").read_text(encoding="utf-8").split("\n")


def section(first_text, last_text, after=0):
    """Lines from the first line containing first_text to the line containing last_text (searching after it)."""
    start = next(i for i, line in enumerate(lines) if first_text in line and i >= after)
    end = next(i for i, line in enumerate(lines) if last_text in line and i > start)
    return start, end


def take(start, end):
    return "\n".join(lines[start:end + 1])


includes_start, includes_end = section("#include <Mod/CppUserModBase.hpp>", "RC_UE_API auto RegisterProcessEventPreCallback")
includes = take(includes_start, includes_end + 1)  # through the namespace's closing brace
assert lines[includes_end + 1].strip() == "}", "callback declaration moved"

mod_dir_start, _ = section("std::filesystem::path ModDir()", "std::string Dev(const char* name)")
_, dev_end = section("std::string Dev(const char* name)", "bool DevFlag(const char* name)")
paths = take(mod_dir_start, dev_end - 1)

thread_start, _ = section("struct LoaderTlsBuild {", "constexpr LoaderTlsBuild LoaderTlsBuilds[]")
on_thread, _ = section("bool OnGameThread()", "return TlsGetValue(index)!=nullptr;")
_, thread_end = section("return TlsGetValue(index)!=nullptr;", "}", on_thread)
thread = take(thread_start, thread_end)

code_start, code_end = section("namespace Code", "bool CallsTo(uintptr_t va,uintptr_t target)")
code = take(code_start, code_end + 1)
assert lines[code_end + 1].strip() == "}", "Code namespace moved"

loader_start, loader_mid = section("namespace Loader", "bool Counters(int32_t& queued,int32_t& inFlight,uint8_t& suspended)")
_, loader_end = section("return p && ReadCounters(p,queued,inFlight,suspended);", "}", loader_mid)
loader = take(loader_start, loader_end) + "\n    }"

safe_start, safe_mid = section("namespace SafePoint", "void Close(RC::Unreal::UObject* object,RC::Unreal::UFunction* function)")
_, safe_end = section("shut=true; gateObject=object;", "}", safe_mid)
safe = take(safe_start, safe_end + 1)
assert lines[safe_end + 1].strip() == "}", "SafePoint namespace moved"


def ours(text):
    return (text.replace("junon-native-identity-events.log", "stages-helper-events.log")
            .replace("Junon Colosseum", "Simulator Stages")
            .replace('"JC-BUILD"', '"SS-BUILD"').replace('"JC-LOADER"', '"SS-LOADER"')
            .replace("; the mod is on", "; streamed stages are available"))


glue = (ROOT / "native" / "src" / "helper_glue.cpp").read_text(encoding="utf-8")
head, tail = glue.split("// ==== COPIED SECTIONS GO HERE ====\n")
out = "\n".join([
    "// GENERATED by tools/make_helper_source.py. Edit helper_glue.cpp or the script, not this file.",
    "// The sections marked 'from Junon Colosseum' are copied unchanged from its helper.",
    includes,
    "",
    head.rstrip("\n"),
    "    // ---- from Junon Colosseum: where the mod's files are ----",
    "    int marker=0;",
    paths,
    "    std::string Shared(const char* name) { return (ModDir()/name).string(); }",
    "    // ---- from Junon Colosseum: is this the game thread? ----",
    ours(thread),
    "    // ---- from Junon Colosseum: checking the game's code bytes ----",
    code,
    "    // ---- from Junon Colosseum: is the package loader busy? ----",
    ours(loader),
    "    // ---- from Junon Colosseum: one unit of work per frame, at a Blueprint tick or camera update ----",
    ours(safe),
    tail.rstrip("\n"),
    "",
])
target = ROOT / "native" / "src" / "main.cpp"
target.write_text(out, encoding="utf-8", newline="\n")
# find_addresses.hpp was copied from Junon too until 2026-11-19; it now has this mod's guarded QwordsEqual (for
# Proton), so it is kept here and not overwritten.
print(f"wrote {target.relative_to(ROOT)} ({len(out.splitlines())} lines)")
